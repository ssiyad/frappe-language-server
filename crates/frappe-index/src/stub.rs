//! The generated `frappe/model/document.pyi` —
//! [24](../../../docs/specs/24-type-integration.md), mechanism A.
//!
//! A `.pyi` replaces a module's types wholesale, so the stub has to be
//! complete. It is: it is `document.py` itself, with `Literal` overloads
//! inserted ahead of the ones it already has. Each new overload is a copy of
//! one of frappe's own, with the DocType parameter narrowed to one name and the
//! return type narrowed to that DocType's controller, so the signatures follow
//! whatever frappe version is installed.

use std::collections::BTreeSet;
use std::path::Path;

use crate::index::{ExtraKind, Index};

/// The calls whose first argument names the DocType of what they return.
pub const CONSTRUCTORS: [&str; 6] = [
    "frappe.get_doc",
    "frappe.get_cached_doc",
    "frappe.get_lazy_doc",
    "frappe.get_last_doc",
    "frappe.new_doc",
    "frappe.get_single",
];

/// Which DocTypes get overloads.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Scope {
    /// Those some Python file constructs by name: pyright's cost grows with
    /// the number of overloads, so this is the default.
    Referenced,
    /// Every DocType with a controller. Measured at about 60× pyright's time
    /// on a large bench; not a supported configuration.
    All,
}

/// A generated stub.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Stub {
    /// The `.pyi` text.
    pub text: String,
    /// How many DocTypes have overloads.
    pub doctypes: usize,
    /// How many overloads were added.
    pub overloads: usize,
}

/// Generate the stub, or say why not. A stub that does not parse is never
/// returned: pyright would read a broken stub instead of frappe's own types.
pub fn generate(index: &Index, scope: Scope) -> Result<Stub, String> {
    let frappe = index
        .apps()
        .iter()
        .find(|app| app.name == "frappe")
        .ok_or("frappe is not installed in this bench")?;
    let path = frappe.package.join("model").join("document.py");
    let source =
        std::fs::read_to_string(&path).map_err(|error| format!("{}: {error}", path.display()))?;

    if scope == Scope::Referenced && !index.occurrences().scanned {
        return Err("the reference table is not built yet".to_string());
    }
    let targets = targets(index, scope);
    let functions = functions(&source)?;
    if !functions.iter().any(|function| function.name == "get_doc") {
        return Err(format!("{} defines no get_doc", path.display()));
    }

    let mut insertions: Vec<(usize, String)> = Vec::new();
    let mut overloads = 0;
    for function in &functions {
        let mut text = String::new();
        let call = format!("frappe.{}", function.name);
        for template in &function.templates {
            for (alias, target) in targets.iter().enumerate() {
                // Only the calls the workspace makes: every overload costs
                // pyright time and memory at every call of that function.
                if !target.calls.contains(&call) {
                    continue;
                }
                // `get_doc("Selling Settings")` with no name reads a Single;
                // that overload is for nothing else.
                if template.single_only && !target.single {
                    continue;
                }
                text.push_str(&template.narrowed(&target.doctype, &format!("_frappe_lsp_{alias}")));
                overloads += 1;
            }
        }
        // A function frappe gives no overloads gets one more, its own
        // signature, so a DocType outside the set still types as before.
        if let Some(fallback) = &function.fallback {
            text.push_str(fallback);
        }
        if !text.is_empty() {
            insertions.push((function.insert_at, text));
        }
    }

    let imports: String = targets
        .iter()
        .enumerate()
        .map(|(alias, target)| {
            format!(
                "from {} import {} as _frappe_lsp_{alias}\n",
                target.module, target.class
            )
        })
        .collect();
    insertions.push((
        import_point(&source),
        format!("from typing import Literal, overload\n{imports}\n"),
    ));
    insertions.extend(reexports(&source));

    insertions.sort_by_key(|(at, _)| std::cmp::Reverse(*at));
    let mut text = source;
    for (at, insertion) in insertions {
        text.insert_str(at, &insertion);
    }
    let commit = frappe.commit_hash.as_deref().unwrap_or("unknown");
    let text = format!(
        "# Generated by frappe-lsp {} from frappe {commit}. Do not edit:\n\
         # it is rewritten whenever the bench changes. Spec 24 of frappe-lsp.\n{text}",
        env!("CARGO_PKG_VERSION")
    );

    let mut parser = frappe_syntax::Language::Python
        .parser()
        .map_err(|error| error.to_string())?;
    let parsed = parser.parse(&text, None).ok_or("the stub did not parse")?;
    if parsed.root_node().has_error() {
        return Err("the generated stub has a syntax error; not written".to_string());
    }

    Ok(Stub {
        text,
        doctypes: targets.len(),
        overloads,
    })
}

/// One DocType and the class its documents are.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
struct Target {
    doctype: String,
    single: bool,
    /// The constructor calls it is named in, or all of them for `Scope::All`.
    calls: BTreeSet<String>,
    module: String,
    class: String,
}

/// The DocTypes in scope with a class to name: the last
/// `override_doctype_class` for it, else its controller. A DocType with
/// neither stays `Document`.
fn targets(index: &Index, scope: Scope) -> Vec<Target> {
    let mut names: std::collections::BTreeMap<String, BTreeSet<String>> = Default::default();
    match scope {
        Scope::Referenced => {
            for (call, doctype) in index.occurrences().constructed() {
                names
                    .entry(doctype.to_string())
                    .or_default()
                    .insert(call.to_string());
            }
        }
        Scope::All => {
            for doctype in index.doctypes() {
                names.insert(
                    doctype.name.clone(),
                    CONSTRUCTORS
                        .iter()
                        .map(|call| (*call).to_string())
                        .collect(),
                );
            }
        }
    }
    names
        .into_iter()
        .filter_map(|(name, calls)| {
            let doctype = index.doctype(&name)?;
            let overridden = index
                .controller_extras(&name)
                .iter()
                .rev()
                .find(|extra| extra.kind == ExtraKind::Override)
                .and_then(|extra| {
                    let (module, class) = extra.dotted.rsplit_once('.')?;
                    Some((module.to_string(), class.to_string()))
                });
            let (module, class) = overridden.or_else(|| {
                let controller = doctype.controller.as_ref()?;
                Some((controller.module.clone(), controller.class_name.clone()))
            })?;
            Some(Target {
                calls,
                single: doctype.is_single,
                doctype: name,
                module,
                class,
            })
        })
        .collect()
}

/// A signature to copy for each DocType.
#[derive(Debug, Clone)]
struct Template {
    name: String,
    /// The parameter list, parentheses included, with `{DOCTYPE}` where the
    /// DocType's annotation goes.
    parameters: String,
    /// The DocType is the only argument: frappe reads it as a Single.
    single_only: bool,
}

impl Template {
    fn narrowed(&self, doctype: &str, class: &str) -> String {
        let literal = format!("Literal[{}]", python_string(doctype));
        format!(
            "@overload\ndef {}{} -> \"{class}\": ...\n\n\n",
            self.name,
            self.parameters.replace("{DOCTYPE}", &literal)
        )
    }
}

/// A covered function in `document.py`: where its overloads go, and what to
/// copy for them.
struct Function {
    name: String,
    insert_at: usize,
    templates: Vec<Template>,
    fallback: Option<String>,
}

fn functions(source: &str) -> Result<Vec<Function>, String> {
    let mut parser = frappe_syntax::Language::Python
        .parser()
        .map_err(|error| error.to_string())?;
    let tree = parser
        .parse(source, None)
        .ok_or("document.py did not parse")?;
    let root = tree.root_node();
    let text = |node: tree_sitter::Node<'_>| &source[node.byte_range()];

    let covered: Vec<&str> = CONSTRUCTORS
        .iter()
        .filter_map(|dotted| dotted.strip_prefix("frappe."))
        .collect();
    let mut found = Vec::new();
    for name in covered {
        // Every module-level definition of it, with its decorators.
        let mut cursor = root.walk();
        let definitions: Vec<(tree_sitter::Node<'_>, tree_sitter::Node<'_>, bool)> = root
            .named_children(&mut cursor)
            .filter_map(|statement| {
                let (outer, function) = match statement.kind() {
                    "function_definition" => (statement, statement),
                    "decorated_definition" => {
                        (statement, statement.child_by_field_name("definition")?)
                    }
                    _ => return None,
                };
                (function.child_by_field_name("name").map(text) == Some(name)).then(|| {
                    let mut inner = outer.walk();
                    let overload = outer.named_children(&mut inner).any(|child| {
                        child.kind() == "decorator" && text(child).trim() == "@overload"
                    });
                    (outer, function, overload)
                })
            })
            .collect();
        let Some((first, _, _)) = definitions.first() else {
            continue;
        };

        let overloads: Vec<_> = definitions
            .iter()
            .filter(|(_, _, overload)| *overload)
            .collect();
        let (templates, fallback) = if overloads.is_empty() {
            // No overloads to copy: copy the implementation, and keep its
            // own signature as the fallback overload.
            let (_, function, _) = definitions[0];
            let Some(parameters) = function.child_by_field_name("parameters") else {
                continue;
            };
            let returns = function
                .child_by_field_name("return_type")
                .map_or(String::new(), |node| format!(" -> {}", text(node)));
            let template = template(name, parameters, source);
            let fallback = format!(
                "@overload\ndef {name}{}{returns}: ...\n\n\n",
                text(parameters)
            );
            (template.into_iter().collect(), Some(fallback))
        } else {
            // The overloads whose first parameter is a DocType name.
            let templates = overloads
                .iter()
                .filter_map(|(_, function, _)| {
                    let parameters = function.child_by_field_name("parameters")?;
                    let first = parameters.named_child(0)?;
                    let annotation = first.child_by_field_name("type").map(text)?;
                    (annotation.trim_matches(['"', '\'']) == "str")
                        .then(|| template(name, parameters, source))
                        .flatten()
                })
                .collect();
            (templates, None)
        };
        found.push(Function {
            name: name.to_string(),
            insert_at: first.start_byte(),
            templates,
            fallback,
        });
    }
    Ok(found)
}

/// The parameter list with its first parameter's annotation replaced by
/// `{DOCTYPE}`, or one added. `(*args, **kwargs)` gets a DocType parameter of
/// its own in front.
fn template(name: &str, parameters: tree_sitter::Node<'_>, source: &str) -> Option<Template> {
    let text = &source[parameters.byte_range()];
    let start = parameters.start_byte();
    let first = parameters.named_child(0)?;
    let local = |offset: usize| offset - start;

    // `*args: Any` is a typed parameter around a splat: still a splat.
    let splat = matches!(
        first.kind(),
        "list_splat_pattern" | "dictionary_splat_pattern"
    ) || first.named_child(0).is_some_and(|inner| {
        matches!(
            inner.kind(),
            "list_splat_pattern" | "dictionary_splat_pattern"
        )
    });
    let rewritten = match first.kind() {
        _ if splat => format!(
            "{}doctype: {{DOCTYPE}}, {}",
            &text[..local(first.start_byte())],
            &text[local(first.start_byte())..]
        ),
        "typed_parameter" | "typed_default_parameter" => {
            let annotation = first.child_by_field_name("type")?;
            format!(
                "{}{{DOCTYPE}}{}",
                &text[..local(annotation.start_byte())],
                &text[local(annotation.end_byte())..]
            )
        }
        "identifier" => format!(
            "{}: {{DOCTYPE}}{}",
            &text[..local(first.end_byte())],
            &text[local(first.end_byte())..]
        ),
        "default_parameter" => {
            let parameter = first.child_by_field_name("name")?;
            format!(
                "{}: {{DOCTYPE}}{}",
                &text[..local(parameter.end_byte())],
                &text[local(parameter.end_byte())..]
            )
        }
        _ => return None,
    };
    let mut cursor = parameters.walk();
    let positional = parameters
        .named_children(&mut cursor)
        .filter(|parameter| {
            !matches!(
                parameter.kind(),
                "positional_separator" | "keyword_separator" | "comment"
            )
        })
        .count();
    Some(Template {
        name: name.to_string(),
        parameters: rewritten,
        // `get_doc(doctype: str, /)`; not `get_single`, whose whole point is that.
        single_only: name == "get_doc" && positional == 1,
    })
}

/// ` as name` after every name a module-level import binds without one.
///
/// In a `.py` file every imported name can be imported from it again; in a
/// `.pyi` only `name as name` is a re-export. `frappe.www.list` imports
/// `get_controller` from `frappe.model.document`, which only imports it, and
/// without this the stub broke every such import.
fn reexports(source: &str) -> Vec<(usize, String)> {
    let Ok(mut parser) = frappe_syntax::Language::Python.parser() else {
        return Vec::new();
    };
    let Some(tree) = parser.parse(source, None) else {
        return Vec::new();
    };
    let mut found = Vec::new();
    // Module level, including inside `if TYPE_CHECKING:` and `try:` there.
    let mut stack = vec![tree.root_node()];
    while let Some(node) = stack.pop() {
        let mut cursor = node.walk();
        for child in node.named_children(&mut cursor) {
            match child.kind() {
                "if_statement" | "try_statement" | "block" | "else_clause" | "elif_clause"
                | "except_clause" | "finally_clause" => stack.push(child),
                "import_from_statement" | "import_statement" => {
                    let mut names = child.walk();
                    for name in child.children_by_field_name("name", &mut names) {
                        let text = &source[name.byte_range()];
                        // `import a.b` binds `a`, which an alias cannot keep.
                        if name.kind() == "dotted_name" && !text.contains('.') {
                            found.push((name.end_byte(), format!(" as {text}")));
                        } else if name.kind() == "dotted_name"
                            && child.kind() == "import_from_statement"
                        {
                            let last = text.rsplit('.').next().unwrap_or(text);
                            found.push((name.end_byte(), format!(" as {last}")));
                        }
                    }
                }
                _ => {}
            }
        }
    }
    found
}

/// After the module docstring and `from __future__` imports, which must come
/// first; everywhere else an import is legal.
fn import_point(source: &str) -> usize {
    let mut parser = match frappe_syntax::Language::Python.parser() {
        Ok(parser) => parser,
        Err(_) => return 0,
    };
    let Some(tree) = parser.parse(source, None) else {
        return 0;
    };
    let root = tree.root_node();
    let mut cursor = root.walk();
    let mut at = 0;
    for statement in root.named_children(&mut cursor) {
        let text = &source[statement.byte_range()];
        let docstring = statement.kind() == "expression_statement"
            && statement
                .named_child(0)
                .is_some_and(|child| child.kind() == "string");
        let future = statement.kind() == "future_import_statement";
        if !(docstring || future || statement.kind() == "comment") || text.is_empty() {
            break;
        }
        at = statement.end_byte();
    }
    // Nothing to skip: the very start, not the end of a first line that may
    // be half of a parenthesised import.
    if at == 0 {
        return 0;
    }
    source[at..]
        .find('\n')
        .map_or(source.len(), |newline| at + newline + 1)
}

/// A Python string literal for `value`.
fn python_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

/// Write `stub` at `<directory>/frappe/model/document.pyi`, unless the same
/// text is already there. Says whether it wrote.
pub fn write(directory: &Path, stub: &Stub) -> std::io::Result<bool> {
    let path = directory.join("frappe").join("model").join("document.pyi");
    if std::fs::read_to_string(&path).is_ok_and(|existing| existing == stub.text) {
        return Ok(false);
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let partial = path.with_extension("pyi.partial");
    std::fs::write(&partial, &stub.text)?;
    std::fs::rename(&partial, &path)?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    const DOCUMENT: &str = r#""""The document module."""
from __future__ import annotations

from typing import overload


@overload
def get_doc(document: "Document", /) -> "Document":
	pass


@overload
def get_doc(doctype: str, name: str, /, *, for_update: bool | None = None) -> "Document":
	pass


def get_doc(*args, **kwargs) -> "Document":
	return None


def new_doc(doctype: str, *, parent_doc=None, **kwargs) -> "Document":
	return None


def get_cached_doc(*args: Any, **kwargs: Any) -> "Document":
	return None


def get_single(doctype):
	return None
"#;

    #[test]
    fn overloads_copy_frappes_own_signatures() {
        let functions = functions(DOCUMENT).expect("parses");
        let get_doc = functions
            .iter()
            .find(|f| f.name == "get_doc")
            .expect("get_doc");
        // Only the overload whose first parameter is a DocType name is copied.
        assert_eq!(get_doc.templates.len(), 1);
        assert!(get_doc.fallback.is_none());
        assert_eq!(
            get_doc.templates[0].narrowed("Sales Invoice", "_c"),
            "@overload\ndef get_doc(doctype: Literal[\"Sales Invoice\"], name: str, /, *, for_update: bool | None = None) -> \"_c\": ...\n\n\n"
        );

        let new_doc = functions
            .iter()
            .find(|f| f.name == "new_doc")
            .expect("new_doc");
        assert!(
            new_doc.templates[0]
                .narrowed("X", "_c")
                .starts_with("@overload\ndef new_doc(doctype: Literal[\"X\"], *,")
        );
        assert!(
            new_doc
                .fallback
                .as_deref()
                .is_some_and(|f| f.contains("-> \"Document\": ..."))
        );

        let cached = functions
            .iter()
            .find(|f| f.name == "get_cached_doc")
            .expect("cached");
        assert!(
            cached.templates[0]
                .narrowed("X", "_c")
                .contains("(doctype: Literal[\"X\"], *args: Any")
        );

        let single = functions
            .iter()
            .find(|f| f.name == "get_single")
            .expect("single");
        assert!(
            single.templates[0]
                .narrowed("X", "_c")
                .contains("(doctype: Literal[\"X\"])")
        );
    }

    #[test]
    fn imports_go_after_the_docstring_and_future_imports() {
        let at = import_point(DOCUMENT);
        assert!(
            DOCUMENT[..at].ends_with("from __future__ import annotations\n"),
            "{:?}",
            &DOCUMENT[..at]
        );
    }

    #[test]
    fn module_level_imports_become_reexports() {
        let source = "import json\nimport frappe.utils\nfrom a.b import c, d as e\n\
                      if TYPE_CHECKING:\n\tfrom x import Y\n\
                      def f():\n\tfrom z import w\n";
        let mut text = source.to_string();
        let mut found = reexports(source);
        found.sort_by_key(|(at, _)| std::cmp::Reverse(*at));
        for (at, insertion) in found {
            text.insert_str(at, &insertion);
        }
        assert_eq!(
            text,
            "import json as json\nimport frappe.utils\nfrom a.b import c as c, d as e\n\
             if TYPE_CHECKING:\n\tfrom x import Y as Y\n\
             def f():\n\tfrom z import w\n"
        );
    }

    #[test]
    fn with_nothing_to_skip_imports_go_first() {
        assert_eq!(import_point("from x import (\n\ta,\n)\n"), 0);
    }

    #[test]
    fn a_doctype_name_is_quoted_safely() {
        assert_eq!(python_string("A \"B\""), "\"A \\\"B\\\"\"");
    }
}
